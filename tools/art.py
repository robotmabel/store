# ------------------------------------------------------------------- canvas --
class Art:
    """Collects defs and body so gradients get unique ids per figure."""

    def __init__(self, pid: str):
        self.pid = pid.replace("/", "-")
        self.defs: list[str] = []
        self.body: list[str] = []
        self._n = 0

    def uid(self, tag: str) -> str:
        self._n += 1
        return f"{self.pid}-{tag}-{self._n}"

    def add(self, s: str) -> None:
        self.body.append(s)

    def define(self, s: str) -> None:
        self.defs.append(s)

    # -- gradients ---------------------------------------------------------
    def lin(self, stops, x1=0.0, y1=0.0, x2=1.0, y2=0.0, tag="lg") -> str:
        gid = self.uid(tag)
        st = "".join(
            f'<stop offset="{o:.4f}" stop-color="{c}"'
            + (f' stop-opacity="{a}"' if a is not None else "")
            + "/>"
            for o, c, a in stops
        )
        self.define(
            f'<linearGradient id="{gid}" x1="{x1}" y1="{y1}" x2="{x2}" y2="{y2}">{st}</linearGradient>'
        )
        return gid

    def rad(self, stops, cx=0.5, cy=0.5, r=0.5, fx=None, fy=None, tag="rg") -> str:
        gid = self.uid(tag)
        f = f' fx="{fx}" fy="{fy}"' if fx is not None else ""
        st = "".join(
            f'<stop offset="{o:.4f}" stop-color="{c}"'
            + (f' stop-opacity="{a}"' if a is not None else "")
            + "/>"
            for o, c, a in stops
        )
        self.define(
            f'<radialGradient id="{gid}" cx="{cx}" cy="{cy}" r="{r}"{f}>{st}</radialGradient>'
        )
        return gid

    def blur(self, px: float) -> str:
        fid = self.uid("bl")
        self.define(
            f'<filter id="{fid}" x="-60%" y="-60%" width="220%" height="220%">'
            f'<feGaussianBlur stdDeviation="{px}"/></filter>'
        )
        return fid

    # Subjects are composed around (500, 520); this zoom makes them fill the
    # frame like a product shot instead of floating in white space.
    ZOOM = 1.15
    PIVOT = (500.0, 520.0)

    def render(self, title: str) -> str:
        px, py = self.PIVOT
        z = self.ZOOM
        return (
            f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {W:.0f} {H:.0f}" '
            f'role="img" aria-label="{esc(title)}" preserveAspectRatio="xMidYMid meet">'
            f"<title>{esc(title)}</title>"
            f"<defs>{''.join(self.defs)}</defs>"
            f'<g transform="translate({px:.1f} {py:.1f}) scale({z}) translate({-px:.1f} {-py:.1f})">'
            f"{''.join(self.body)}"
            "</g></svg>"
        )


def esc(s: str) -> str:
    return (
        str(s).replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;").replace('"', "&quot;")
    )


# ---------------------------------------------------------------- primitives --
def ground(a: Art, cx: float, cy: float, rx: float, ry: float, op=0.20) -> None:
    """One soft contact shadow. Always the first thing drawn."""
    g = a.rad(
        [(0.0, "#0b0f14", op), (0.55, "#0b0f14", op * 0.45), (1.0, "#0b0f14", 0.0)],
        tag="gnd",
    )
    f = a.blur(rx * 0.055)
    a.add(f'<ellipse cx="{cx:.1f}" cy="{cy:.1f}" rx="{rx:.1f}" ry="{ry:.1f}" fill="url(#{g})" filter="url(#{f})"/>')


def body_ramp(a: Art, m: list[str], horizontal=True, tag="body") -> str:
    """The standard curved-surface ramp: key light from the upper-left."""
    stops = [
        (0.00, m[1], None),
        (0.10, m[2], None),
        (0.26, m[3], None),
        (0.34, m[4], None),
        (0.42, m[3], None),
        (0.62, m[2], None),
        (0.86, m[1], None),
        (1.00, m[0], None),
    ]
    if horizontal:
        return a.lin(stops, 0, 0, 1, 0, tag=tag)
    return a.lin(stops, 0, 0, 0, 1, tag=tag)


def cap_ramp(a: Art, m: list[str], tag="cap") -> str:
    """Top face of a cylinder — light pools upper-left, falls to the far rim."""
    return a.rad(
        [(0.0, m[4], None), (0.34, m[3], None), (0.72, m[2], None), (1.0, m[1], None)],
        cx=0.36, cy=0.30, r=0.78, tag=tag,
    )


def cylinder(a: Art, cx: float, top: float, d: float, h: float, m: list[str],
             squash=0.26, cap=True, rim=True) -> dict:
    """Upright cylinder seen slightly from above. Returns key geometry."""
    r = d / 2.0
    ry = r * squash
    bot = top + h
    grad = body_ramp(a, m)
    # side wall
    a.add(
        f'<path d="M {cx-r:.1f} {top:.1f} L {cx-r:.1f} {bot:.1f} '
        f'A {r:.1f} {ry:.1f} 0 0 0 {cx+r:.1f} {bot:.1f} '
        f'L {cx+r:.1f} {top:.1f} Z" fill="url(#{grad})"/>'
    )
    # bottom shade
    sh = a.lin([(0, "#000", 0.0), (1, "#000", 0.30)], 0, 0, 0, 1, tag="bsh")
    a.add(
        f'<path d="M {cx-r:.1f} {bot-h*0.30:.1f} L {cx-r:.1f} {bot:.1f} '
        f'A {r:.1f} {ry:.1f} 0 0 0 {cx+r:.1f} {bot:.1f} '
        f'L {cx+r:.1f} {bot-h*0.30:.1f} Z" fill="url(#{sh})"/>'
    )
    if cap:
        cg = cap_ramp(a, m)
        a.add(f'<ellipse cx="{cx:.1f}" cy="{top:.1f}" rx="{r:.1f}" ry="{ry:.1f}" fill="url(#{cg})"/>')
    if rim:
        a.add(
            f'<ellipse cx="{cx:.1f}" cy="{top:.1f}" rx="{r:.1f}" ry="{ry:.1f}" '
            f'fill="none" stroke="{m[4]}" stroke-opacity="0.55" stroke-width="1.6"/>'
        )
    return {"cx": cx, "top": top, "bot": bot, "r": r, "ry": ry}


def ring(a: Art, cx: float, cy: float, r: float, ry: float, t: float, m: list[str], op=1.0) -> None:
    """A band around a cylinder — anodised collar, bearing race, encoder ring."""
    g = body_ramp(a, m, tag="ring")
    a.add(
        f'<path d="M {cx-r:.1f} {cy:.1f} L {cx-r:.1f} {cy+t:.1f} '
        f'A {r:.1f} {ry:.1f} 0 0 0 {cx+r:.1f} {cy+t:.1f} '
        f'L {cx+r:.1f} {cy:.1f} A {r:.1f} {ry:.1f} 0 0 1 {cx-r:.1f} {cy:.1f} Z" '
        f'fill="url(#{g})" opacity="{op}"/>'
    )


def disc(a: Art, cx: float, cy: float, r: float, ry: float, m: list[str], inset=0.0) -> None:
    g = cap_ramp(a, m, tag="disc")
    a.add(f'<ellipse cx="{cx:.1f}" cy="{cy:.1f}" rx="{r:.1f}" ry="{ry:.1f}" fill="url(#{g})"/>')


def bolt_circle(a: Art, cx: float, cy: float, r: float, ry: float, n: int, br=7.0,
                m=None, start=0.0) -> None:
    """Counter-bored fastener holes on an ellipse — the detail that reads 'flange'."""
    m = m or mat("steel")
    for i in range(n):
        th = start + 2 * math.pi * i / n
        x = cx + r * math.cos(th)
        y = cy + ry * math.sin(th)
        a.add(f'<ellipse cx="{x:.1f}" cy="{y:.1f}" rx="{br:.1f}" ry="{br*0.62:.1f}" fill="{m[0]}" opacity="0.85"/>')
        a.add(f'<ellipse cx="{x:.1f}" cy="{y-1.2:.1f}" rx="{br*0.66:.1f}" ry="{br*0.40:.1f}" fill="#05070a" opacity="0.75"/>')


def screw_head(a: Art, x: float, y: float, r: float, m=None, kind="hex") -> None:
    m = m or mat("steel")
    g = a.rad([(0, m[4], None), (0.5, m[3], None), (1, m[1], None)], cx=0.38, cy=0.34, r=0.72, tag="sc")
    a.add(f'<circle cx="{x:.1f}" cy="{y:.1f}" r="{r:.1f}" fill="url(#{g})"/>')
    a.add(f'<circle cx="{x:.1f}" cy="{y:.1f}" r="{r:.1f}" fill="none" stroke="{m[0]}" stroke-opacity=".55" stroke-width="{r*0.14:.2f}"/>')
    if kind == "hex":
        pts = " ".join(
            f"{x + r*0.52*math.cos(math.pi/6 + k*math.pi/3):.1f},{y + r*0.52*math.sin(math.pi/6 + k*math.pi/3):.1f}"
            for k in range(6)
        )
        a.add(f'<polygon points="{pts}" fill="#0a0d11" opacity="0.82"/>')
    else:
        a.add(f'<rect x="{x-r*0.58:.1f}" y="{y-r*0.12:.1f}" width="{r*1.16:.1f}" height="{r*0.24:.1f}" rx="{r*0.06:.1f}" fill="#0a0d11" opacity="0.8"/>')


def spec_sheen(a: Art, x: float, y: float, w: float, h: float, rx=0.0, op=0.30, angle=0.0) -> None:
    """A soft diagonal specular wipe laid over a face."""
    g = a.lin(
        [(0.0, "#ffffff", 0.0), (0.38, "#ffffff", op), (0.52, "#ffffff", op * 0.5), (1.0, "#ffffff", 0.0)],
        0, 0, 1, 1, tag="sheen",
    )
    tr = f' transform="rotate({angle} {x+w/2:.1f} {y+h/2:.1f})"' if angle else ""
    a.add(f'<rect x="{x:.1f}" y="{y:.1f}" width="{w:.1f}" height="{h:.1f}" rx="{rx:.1f}" fill="url(#{g})"{tr}/>')


def edge_light(a: Art, d: str, m: list[str], w=1.8, op=0.7) -> None:
    a.add(f'<path d="{d}" fill="none" stroke="{m[4]}" stroke-opacity="{op}" stroke-width="{w}" stroke-linecap="round"/>')


def box3d(a: Art, x: float, y: float, w: float, h: float, depth: float, m: list[str],
          rx=10.0, skew=0.52) -> dict:
    """Front-facing box with a visible top and right face. depth is in y units."""
    dx = depth * skew
    dy = -depth * 0.58
    top = f"M {x:.1f} {y:.1f} L {x+dx:.1f} {y+dy:.1f} L {x+w+dx:.1f} {y+dy:.1f} L {x+w:.1f} {y:.1f} Z"
    side = f"M {x+w:.1f} {y:.1f} L {x+w+dx:.1f} {y+dy:.1f} L {x+w+dx:.1f} {y+dy+h:.1f} L {x+w:.1f} {y+h:.1f} Z"
    gt = a.lin([(0, m[4], None), (1, m[3], None)], 0, 0, 0.4, 1, tag="top")
    gs = a.lin([(0, m[1], None), (1, m[0], None)], 0, 0, 1, 0.2, tag="side")
    gf = a.lin([(0, m[3], None), (0.45, m[2], None), (1, m[1], None)], 0, 0, 0.35, 1, tag="face")
    a.add(f'<path d="{top}" fill="url(#{gt})"/>')
    a.add(f'<path d="{side}" fill="url(#{gs})"/>')
    a.add(f'<rect x="{x:.1f}" y="{y:.1f}" width="{w:.1f}" height="{h:.1f}" rx="{rx:.1f}" fill="url(#{gf})"/>')
    edge_light(a, f"M {x+rx:.1f} {y:.1f} L {x+w-rx:.1f} {y:.1f}", m, 2.0, 0.55)
    return {"fx": x, "fy": y, "fw": w, "fh": h, "dx": dx, "dy": dy}


def cable(a: Art, pts: list[tuple[float, float]], w=13.0, m=None, sleeve=True) -> None:
    """A drooping cable drawn as a smooth polyline with a highlight core."""
    m = m or mat("plastic_bk")
    d = f"M {pts[0][0]:.1f} {pts[0][1]:.1f}"
    for i in range(1, len(pts)):
        px, py = pts[i - 1]
        x, y = pts[i]
        cx1, cy1 = px + (x - px) * 0.45, py + (y - py) * 0.10
        cx2, cy2 = px + (x - px) * 0.55, py + (y - py) * 0.90
        d += f" C {cx1:.1f} {cy1:.1f} {cx2:.1f} {cy2:.1f} {x:.1f} {y:.1f}"
    a.add(f'<path d="{d}" fill="none" stroke="{m[0]}" stroke-width="{w:.1f}" stroke-linecap="round"/>')
    a.add(f'<path d="{d}" fill="none" stroke="{m[2]}" stroke-width="{w*0.66:.1f}" stroke-linecap="round"/>')
    a.add(f'<path d="{d}" fill="none" stroke="{m[4]}" stroke-opacity="0.45" stroke-width="{w*0.20:.1f}" '
          f'stroke-linecap="round" transform="translate({-w*0.16:.1f},{-w*0.18:.1f})"/>')


