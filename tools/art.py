    body = mat(o.get("body", "alu_dark"))
    d = o.get("d", 400.0)
    h = o.get("h", 130.0)
    top = 500 - h / 2 - 20
    ground(a, CX, top + h + 54, d * 0.60, d * 0.13)
    cyl = cylinder(a, CX, top, d, h, body)
    ring(a, CX, top + h * 0.50, cyl["r"], cyl["ry"], h * 0.16, mat("anod_black"))
    disc(a, CX, top, cyl["r"] * 0.80, cyl["r"] * 0.80 * 0.26, mat("alu"))
    bolt_circle(a, CX, top, cyl["r"] * 0.56, cyl["r"] * 0.56 * 0.26, 8, br=11, m=mat("alu_dark"))
    # output shaft with flat
    sh = cyl["r"] * 0.17
    a.add(f'<ellipse cx="{CX:.1f}" cy="{top-16:.1f}" rx="{sh:.1f}" ry="{sh*0.30:.1f}" fill="{mat("steel")[3]}"/>')
    a.add(f'<rect x="{CX-sh:.1f}" y="{top-16:.1f}" width="{sh*2:.1f}" height="16" fill="{mat("steel")[2]}"/>')
    spec_sheen(a, CX - d * 0.40, top + h * 0.12, d * 0.16, h * 0.70, rx=8, op=0.24)
    if o.get("cable", True):
        cable(a, [(CX + cyl["r"] * 0.78, top + h * 0.70), (CX + d * 0.66, top + h + 26), (CX + d * 0.60, top + h + 118)], 12)


