    m = mat(o.get("body", "steel"))
    R = 300.0
    ground(a, CX, 830, 250, 38)
    n = 42
    og = a.rad([(0, m[4], None), (0.42, m[3], None), (1, m[1], None)], cx=0.36, cy=0.30, r=0.84, tag="gb")
    a.add(f'<circle cx="{CX:.1f}" cy="500" r="{R:.1f}" fill="url(#{og})"/>')
    for i in range(n):
        th = 2 * math.pi * i / n
        x1, y1 = CX + R * 0.90 * math.cos(th), 500 + R * 0.90 * math.sin(th)
        x2, y2 = CX + R * math.cos(th), 500 + R * math.sin(th)
