"""
art.py — parametric SVG product illustrations for the MABEL Robotics store.

Every product figure on the site is generated by this module. Nothing is drawn
by hand and nothing is a photograph, so the whole catalogue shares one lighting
model, one material vocabulary and one camera.

Camera      three-quarter-ish, slightly above the part, orthographic.
Key light   upper-left, 35 deg. Fill from the lower-right at ~18% strength.
Ground      one soft contact ellipse; the art is otherwise transparent so it
            sits on white or on the #f5f5f7 band without a seam.
Canvas      1000 x 1000 user units, the subject inside a 720 unit safe box.
"""

