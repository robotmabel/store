    ground(a, CX, 876, 235, 40)
    box3d(a, CX - 116, 706, 232, 146, 58, jm, rx=24)
    for i in range(5):
        a.add(f'<rect x="{CX-94+i*39:.1f}" y="{722:.1f}" width="24" height="114" rx="8" fill="{jm[4]}" opacity=".16"/>')
    # palm — drawn before the thumb so the thumb root sits on top of it
    box3d(a, CX - 146, 486, 292, 226, 72, m, rx=44)

    def finger(fx, base, lengths, w0, lean):
        a.add(f'<g transform="rotate({lean:.1f} {fx:.1f} {base:.1f})">')
        top = base
        for j, L in enumerate(lengths):
            ww = w0 * (1.0 - j * 0.11)
            top -= L
            box3d(a, fx - ww / 2, top, ww, L, 30, m, rx=ww * 0.44)
            # knuckle: a soft shaded band, not a dot
            a.add(f'<rect x="{fx-ww/2:.1f}" y="{top+L-11:.1f}" width="{ww:.1f}" height="16" rx="8" fill="{jm[3]}" opacity=".55"/>')
            a.add(f'<circle cx="{fx-ww*0.30:.1f}" cy="{top+L-3:.1f}" r="{ww*0.10:.1f}" fill="{jm[1]}" opacity=".8"/>')
            top -= 9
        # fingertip pad
        a.add(f'<ellipse cx="{fx:.1f}" cy="{top+16:.1f}" rx="{w0*0.34:.1f}" ry="{w0*0.22:.1f}" fill="{mat("silicone")[4]}" opacity=".55"/>')
        a.add("</g>")

    for i, (dxp, lean) in enumerate(((-94, -7.0), (-31, -2.2), (31, 2.2), (94, 7.0))):
        finger(CX + dxp, 492, [(86, 72, 56), (96, 80, 60), (92, 76, 58), (76, 64, 50)][i], 56, lean)
    # opposed thumb, hinged off the palm's lower-left corner
    a.add(f'<g transform="rotate(-52 {CX-132:.1f} 660)">')
    a.add(f'<circle cx="{CX-132:.1f}" cy="660" r="30" fill="{jm[2]}"/>')
    box3d(a, CX - 165, 548, 66, 116, 40, m, rx=30)
    a.add(f'<rect x="{CX-165:.1f}" y="{653:.1f}" width="66" height="16" rx="8" fill="{jm[3]}" opacity=".55"/>')
    box3d(a, CX - 161, 452, 58, 92, 36, m, rx=27)
    a.add(f'<rect x="{CX-161:.1f}" y="{533:.1f}" width="58" height="15" rx="7" fill="{jm[3]}" opacity=".55"/>')
    a.add(f'<ellipse cx="{CX-132:.1f}" cy="{466:.1f}" rx="20" ry="13" fill="{mat("silicone")[4]}" opacity=".55"/>')
    a.add("</g>")
    a.add(f'<rect x="{CX-104:.1f}" y="{522:.1f}" width="208" height="146" rx="26" fill="{m[1]}" opacity=".38"/>')
    spec_sheen(a, CX - 136, 500, 74, 198, rx=34, op=0.26)

