def f_joint_module(a: Art, o: dict) -> None:
    """DAMIAO / generic integrated BLDC joint module: stator can, anodised
    collar, output flange with a bolt circle, and a rear cable gland."""
    body = mat(o.get("body", "anod_black"))
    accent = mat(o.get("accent", "anod_red"))
    d = o.get("d", 380.0)
    h = o.get("h", 250.0)
    top = 500 - h / 2 - 40
    ground(a, CX, top + h + 62, d * 0.62, d * 0.15)

    # rear housing (driver box) peeking below
    if o.get("driver", True):
        dw, dh = d * 0.78, h * 0.30
        box3d(a, CX - dw / 2, top + h - dh * 0.15, dw, dh, 40, mat("anod_grey"), rx=10)

    cyl = cylinder(a, CX, top, d, h, body)
    # anodised collar 1/3 down
    ring(a, CX, top + h * 0.36, cyl["r"], cyl["ry"], h * 0.115, accent)
    # cooling fins
    fin = a.lin([(0, "#000", 0.0), (0.5, "#000", 0.22), (1, "#000", 0.0)], 0, 0, 0, 1, tag="fin")
    for i in range(9):
        fx = CX - cyl["r"] + 16 + i * (d - 32) / 8.0
        a.add(f'<rect x="{fx:.1f}" y="{top + h*0.55:.1f}" width="4" height="{h*0.30:.1f}" fill="url(#{fin})"/>')
    # output flange on top
    fr = cyl["r"] * 0.74
    disc(a, CX, top, fr, fr * 0.26, mat("alu"))
    a.add(f'<ellipse cx="{CX:.1f}" cy="{top:.1f}" rx="{fr:.1f}" ry="{fr*0.26:.1f}" fill="none" stroke="{body[0]}" stroke-opacity=".45" stroke-width="2"/>')
    bolt_circle(a, CX, top, fr * 0.62, fr * 0.62 * 0.26, o.get("bolts", 6), br=fr * 0.075, m=mat("alu_dark"))
    # centre bore
    hr = fr * 0.24
    a.add(f'<ellipse cx="{CX:.1f}" cy="{top:.1f}" rx="{hr:.1f}" ry="{hr*0.26:.1f}" fill="#0a0d11" opacity=".9"/>')
    spec_sheen(a, CX - d * 0.42, top + h * 0.10, d * 0.20, h * 0.72, rx=10, op=0.22)
    # cable gland + pigtail
    if o.get("cable", True):
        gx = CX + cyl["r"] * 0.72
        gy = top + h * 0.74
        a.add(f'<rect x="{gx:.1f}" y="{gy:.1f}" width="30" height="26" rx="7" fill="{mat("anod_grey")[1]}"/>')
        cable(a, [(gx + 28, gy + 13), (gx + 92, gy + 34), (gx + 118, gy + 96)], 12)


def f_harmonic_joint(a: Art, o: dict) -> None:
    """EYou PHU-class harmonic joint: wide, shallow, hollow bore, CANopen."""
    body = mat(o.get("body", "anod_black"))
    d = o.get("d", 470.0)
    h = o.get("h", 175.0)
    top = 500 - h / 2 - 10
    ground(a, CX, top + h + 58, d * 0.60, d * 0.13)
    cyl = cylinder(a, CX, top, d, h, body)
