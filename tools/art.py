    a.add(f'<circle cx="{CX:.1f}" cy="500" r="{R*0.70:.1f}" fill="{m[1]}" opacity=".5"/>')
    for i in range(3):
        th = 2 * math.pi * i / 3 - math.pi / 2
        px, py = CX + R * 0.40 * math.cos(th), 500 + R * 0.40 * math.sin(th)
        pg = a.rad([(0, m[4], None), (0.5, m[3], None), (1, m[1], None)], cx=0.36, cy=0.32, r=0.8, tag="pl")
        a.add(f'<circle cx="{px:.1f}" cy="{py:.1f}" r="{R*0.24:.1f}" fill="url(#{pg})"/>')
